# Menggabungkan list dengan extend()
animals = ["Ayam", "Bebek", "Cicak"]
otherAnimals = ["Domba", "Gajah"]
animals.extend(otherAnimals)
print(animals)

# Menggabungkan list dengan operator +
fruits = ["Apel", "Mangga"]
otherFruits = ["Durian", "Jambu"]
allFruits = fruits + otherFruits
print(allFruits)