a = 5
b = 8

# Perbandingan sama dengan
c = a == b
# Perbandingan tidak sama dengan
d = a != b
# Perbandingan lebih kecil dari
e = a < b
# Perbandingan lebih kecil atau sama dengan
f = a <= b
# Perbandingan lebih besar dari
g = a > b
# Perbandingan lebih besar atau sama dengan
h = a >= b

# Cetak seluruh hasil
print(c)  # False
print(d)  # True
print(e)  # True
print(f)  # True
print(g)  # False
print(h)  # False